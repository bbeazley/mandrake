/// The cosine table; entry `i` equals `SINE[(i + 256) % 1024]`.
pub const COSINE: [i16; 1024] = {
    let mut t = [0i16; 1024];
    let mut i = 0;
    while i < 1024 {
        t[i] = SINE[(i + 256) % 1024];
        i += 1;
    }
    t
};

/// The tangent table: `(sine << 14) / cosine`, `i32::MIN` where cosine is 0, and 0 at `0x200`.
pub const TANGENT: [i32; 1024] = {
    let mut t = [0i32; 1024];
    let mut i = 0;
    while i < 1024 {
        let (s, c) = (SINE[i] as i32, COSINE[i] as i32);
        t[i] = if i == 0x200 {
            0
        } else if c == 0 {
            i32::MIN
        } else {
            (s << 14) / c
        };
        i += 1;
    }
    t
};

/// The three tables side by side for callers that index `trig.cosine[i]`/`trig.sine[i]`.
pub struct TrigTables {
    pub cosine: [i16; 1024],
    pub sine: [i16; 1024],
    pub tangent: [i32; 1024],
}

static TABLES: TrigTables = TrigTables {
    cosine: COSINE,
    sine: SINE,
    tangent: TANGENT,
};

#[inline]
pub fn trig_tables() -> &'static TrigTables {
    &TABLES
}

/// Table index of a 16-bit angle: `((angle + 0x20) & 0xffff) >> 6`.
#[inline]
pub const fn angle_index(angle: u16) -> usize {
    (angle.wrapping_add(0x20) >> 6) as usize
}

/// Unsigned integer square root, rounded to the nearest integer.
#[inline]
pub const fn isqrt(n: u32) -> u32 {
    isqrt64_round(n as u64) as u32
}

/// Rounded integer square root of `dx^2 + dy^2`, clamped to `0x7fff` when a delta is outside
/// `-0x7fff..=0x7ffe` or the result exceeds `0x7fff`.
pub const fn distance2d(dx: i32, dy: i32) -> i32 {
    const fn in_range(v: i32) -> bool {
        -0x7fff <= v && v <= 0x7ffe
    }
    if !in_range(dx) || !in_range(dy) {
        return 0x7fff;
    }
    let s = (dx * dx) as u32 + (dy * dy) as u32;
    let r = isqrt(s) as i32;
    if r > 0x7fff { 0x7fff } else { r }
}

/// Angle of `(x, y)` from the tangent table: nearest of the 1024 table angles, ties keeping the higher.
pub fn arctangent(x: i32, y: i32) -> u16 {
    if x == 0 {
        return if y < 0 { 0xc000 } else { 0x4000 };
    }
    let t = y.wrapping_shl(14).wrapping_div(x);
    if t == 0 {
        return if x < 0 { 0x8000 } else { 0 };
    }
    // The quadrant's base: entries `0..` when y > 0, else `512..`, plus 256 when t < 0.
    let base = if y > 0 { 0 } else { 512 } + if t < 0 { 256 } else { 0 };
    let tab = &TANGENT[base..];
    // The lower bound of t in tab[1..256).
    let (mut lo, mut count) = (1usize, 255usize);
    while count > 0 {
        let step = count >> 1;
        let mid = lo + step;
        if t > tab[mid] {
            lo = mid + 1;
            count -= step + 1;
        } else {
            count = step;
        }
    }
    // The nearer neighbour (ties keep `lo`).
    if lo <= 0xff && tab[lo].wrapping_sub(t) > t.wrapping_sub(tab[lo - 1]) {
        lo -= 1;
    }
    (((lo + base) << 6) & 0xffff) as u16
}

#[cfg(test)]
mod tests {
    extern crate std;
    use super::*;

    /// The engine's table build, as `mandrake_sim::engine_move::trig_tables` does it: `sincos` of
    /// `i * TAU * (1 / 1024)`, `x * 16384 + 0.5` truncated, the four axes exact.
    fn engine_sin_cos(i: usize) -> (i16, i16) {
        match i {
            0x000 => (0, 0x4000),
            0x100 => (0x4000, 0),
            0x200 => (0, -0x4000),
            0x300 => (-0x4000, 0),
            _ => {
                let (s, c) = (i as f64 * core::f64::consts::TAU * 0.000_976_562_5).sin_cos();
                (
                    (s * 16384.0 + 0.5) as i32 as i16,
                    (c * 16384.0 + 0.5) as i32 as i16,
                )
            }
        }
    }

    #[test]
    fn tables_match_the_engines_build() {
        for i in 0..1024 {
            let (s, c) = engine_sin_cos(i);
            assert_eq!((SINE[i], COSINE[i]), (s, c), "entry {i}");
            let tan = match i {
                0x200 => 0,
                _ if c == 0 => i32::MIN,
                _ => (i32::from(s) << 14) / i32::from(c),
            };
            assert_eq!(TANGENT[i], tan, "tangent {i}");
        }
        assert_eq!((COSINE[128], SINE[128]), (11585, 11585));
        assert_eq!(COSINE[384], -11584);
    }

    #[test]
    fn isqrt_rounds_to_nearest() {
        for k in 0u32..=0xffff {
            let sq = k * k;
            assert_eq!(isqrt(sq), k);
            assert_eq!(isqrt(sq + k), k, "{k}^2 + {k}");
            assert_eq!(isqrt(sq + k + 1), k + 1, "{k}^2 + {k} + 1");
        }
        assert_eq!(isqrt(u32::MAX), 0x1_0000);
    }

    #[test]
    fn distance2d_clamps_like_the_engine() {
        assert_eq!(distance2d(300, 400), 500);
        assert_eq!(distance2d(-0x7fff, -0x7fff), 0x7fff);
        assert_eq!(distance2d(0x7ffe, 0), 0x7ffe);
        assert_eq!(distance2d(0x7fff, 0), 0x7fff);
        assert_eq!(distance2d(0, -0x8000), 0x7fff);
        assert_eq!(distance2d(i32::MIN, i32::MAX), 0x7fff);
    }

    #[test]
    fn arctangent_maps_every_table_angle_to_itself() {
        assert_eq!(arctangent(0, 0), 0x4000);
        assert_eq!(arctangent(-7, 0), 0x8000);
        assert_eq!(arctangent(100, -100), 0xe000);
        let _ = arctangent(-1, 0x20000);
        for i in 0..1024 {
            let a = arctangent(i32::from(COSINE[i]), i32::from(SINE[i]));
            assert_eq!(a, ((i << 6) & 0xffff) as u16, "entry {i}");
        }
    }
}
